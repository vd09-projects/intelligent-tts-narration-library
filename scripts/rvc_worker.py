# DSP core — pure functions, one per PILOT_REPORT §4 stage. No I/O, no globals.
# Each magic constant cites its §4.x subsection so the port is auditable.
# ══════════════════════════════════════════════════════════════════════════════

SR_IN = 16000            # §4: sr_in — contentvec/rmvpe operate at 16 kHz
SR_OUT = 40000           # §4: tgt — net_g emits 40 kHz directly (100 Hz frames ×400)
HOP = 160                # §4: window/hop — f0 frame hop at 16 kHz
T_PAD = 16000            # §4: x_pad 1 => t_pad 16 000 samples (reflect pad)
TRIM = 40000             # §4.7: [40000:-40000] trim on the 40 kHz output


def load_source(path: str) -> np.ndarray:
    """§4.1 Load: decode -> mono -> soxr VHQ resample to 16 kHz -> normalize.

    Returns float32 mono @ 16 kHz. Normalize peak/0.95, dividing only if >1
    (Applio: audio_max = |peak|/0.95; if audio_max > 1: audio /= audio_max).
    """
    data, sr = sf.read(path, dtype="float32", always_2d=False)
    if data.ndim > 1:                                  # mono = channel mean
        data = data.mean(axis=1)
    data = np.ascontiguousarray(data, dtype=np.float32)
    if sr != SR_IN:                                    # §4.1 soxr VHQ resample
        data = soxr.resample(data, sr, SR_IN, quality="VHQ").astype(np.float32)
    peak = float(np.abs(data).max()) if data.size else 0.0
    audio_max = peak / 0.95                            # §4.1 normalize peak/0.95
    if audio_max > 1.0:
        data = (data / audio_max).astype(np.float32)
    return data


def highpass(x: np.ndarray) -> np.ndarray:
    """§4.2 High-pass: Butterworth N=5, cutoff 48 Hz, fs 16 000, zero-phase."""
    b, a = signal.butter(N=5, Wn=48, btype="high", fs=SR_IN)   # §4.2 N=5 / 48 Hz
    return signal.filtfilt(b, a, x).astype(np.float32)         # §4.2 zero-phase filtfilt


def reflect_pad(x: np.ndarray, pad: int = T_PAD) -> np.ndarray:
    """§4.3 Reflect-pad ±16 000 samples."""
    return np.pad(x, (pad, pad), mode="reflect").astype(np.float32)


# --- §4.4 f0 (rmvpe) ----------------------------------------------------------
# cents_mapping baked constant (§4.4): 20·arange(360)+1997.3794084376191, padded
# (4,4) to length 368 for the ±4-bin weighted-average decode.
_CENTS_MAPPING = np.pad(
    20.0 * np.arange(360) + 1997.3794084376191, (4, 4)  # §4.4
).astype(np.float64)

# Coarse-pitch mapping bounds (§4.4): f0 50..1100 Hz -> mel -> linear 1..255.
_F0_MIN = 50.0
_F0_MAX = 1100.0
_F0_MEL_MIN = 1127.0 * np.log(1.0 + _F0_MIN / 700.0)     # §4.4 f0_mel=1127·ln(1+f0/700)
_F0_MEL_MAX = 1127.0 * np.log(1.0 + _F0_MAX / 700.0)


def _rmvpe_mel(x_padded: np.ndarray, melbasis: np.ndarray) -> np.ndarray:
    """§4.4 mel front-end: STFT (n_fft 1024/hop 160/win 1024, Hann-periodic,
    center reflect) -> |STFT| -> melbasis @ mag -> log(clip(mel, 1e-5)).

    Returns log-mel [128, F] for the rmvpe ONNX net.
    """
    stft = librosa.stft(                                # §4.4 STFT
        x_padded,
        n_fft=1024,
        hop_length=HOP,
        win_length=1024,
        window="hann",                                  # §4.4 librosa 'hann' == periodic
        center=True,
        pad_mode="reflect",
    )
    mag = np.abs(stft).astype(np.float32)               # §4.4 magnitude = |STFT| [513, F]
    mel = melbasis.astype(np.float32) @ mag             # §4.4 melbasis[128,513] @ mag
    log_mel = np.log(np.clip(mel, 1e-5, None))          # §4.4 log(clip(mel, 1e-5))
    return log_mel.astype(np.float32)


def _decode_f0(salience: np.ndarray, thred: float = 0.03) -> np.ndarray:
    """§4.4 decode: weighted average of cents_mapping over ±4 bins around argmax,
    then f0 = 10·2^(cents/1200); salience ≤ 0.03 -> 0."""
    center = np.argmax(salience, axis=1)                          # §4.4 argmax per frame
    padded = np.pad(salience, ((0, 0), (4, 4)))                  # §4.4 pad (4,4)
    center = center + 4
    starts = center - 4
    ends = center + 5
    todo_sal = np.stack([padded[i, starts[i]:ends[i]] for i in range(padded.shape[0])])
    todo_cents = np.stack([_CENTS_MAPPING[starts[i]:ends[i]] for i in range(padded.shape[0])])
    product_sum = np.sum(todo_sal * todo_cents, axis=1)          # §4.4 weighted avg
    weight_sum = np.sum(todo_sal, axis=1)
    cents = product_sum / weight_sum
    maxx = np.max(padded, axis=1)
    cents[maxx <= thred] = 0.0                                    # §4.4 salience ≤ 0.03 -> 0
    f0 = 10.0 * (2.0 ** (cents / 1200.0))                        # §4.4 f0 = 10·2^(cents/1200)
    f0[f0 == 10.0] = 0.0                                          # cents==0 -> unvoiced
    return f0.astype(np.float64)


def _coarse_f0(f0: np.ndarray) -> np.ndarray:
    """§4.4 coarse: f0_mel = 1127·ln(1+f0/700), linear-map to 1..255, rint."""
    f0_mel = 1127.0 * np.log(1.0 + f0 / 700.0)                   # §4.4
    voiced = f0_mel > 0
    f0_mel[voiced] = (f0_mel[voiced] - _F0_MEL_MIN) * 254.0 / (_F0_MEL_MAX - _F0_MEL_MIN) + 1.0
    f0_mel[f0_mel <= 1] = 1.0
    f0_mel[f0_mel > 255] = 255.0
    return np.rint(f0_mel).astype(np.int64)                      # §4.4 rint -> 1..255


def f0_rmvpe(x_padded: np.ndarray, rmvpe_sess: ort.InferenceSession,
             melbasis: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """§4.4 Full f0 stage. Returns (pitch_coarse int64[F], pitchf float32[F])."""
    log_mel = _rmvpe_mel(x_padded, melbasis)                     # [128, F]
    n_frames = log_mel.shape[1]
    # §4.4 pad frames to a multiple of 32 (reflect), run rmvpe.onnx, slice back.
    target = 32 * ((n_frames - 1) // 32 + 1)
    pad_amt = target - n_frames
    if pad_amt > 0:
        log_mel = np.pad(log_mel, ((0, 0), (0, pad_amt)), mode="reflect")
    mel_in = log_mel[np.newaxis, :, :].astype(np.float32)        # [1,128,F_pad]
    salience = rmvpe_sess.run(["hidden"], {"mel": mel_in})[0][0]  # [F_pad, 360]
    salience = salience[:n_frames]                               # §4.4 slice back to n_frames
    f0 = _decode_f0(salience, thred=0.03)                        # §4.4 decode + threshold
    pitch = _coarse_f0(f0.copy())                               # coarse buckets 1..255
    pitchf = f0.astype(np.float32)                              # fine f0 (Hz)
    return pitch, pitchf


def contentvec_feats(x16k_padded: np.ndarray,
                     cv_sess: ort.InferenceSession) -> np.ndarray:
    """§4.5a contentvec: audio 16k [1,T] -> feats [Tc, 768]."""
    audio = x16k_padded[np.newaxis, :].astype(np.float32)       # [1, T_samp]
    feats = cv_sess.run(["feats"], {"audio": audio})[0][0]      # [Tc, 768]
    return feats.astype(np.float32)


def index_blend(feats: np.ndarray, index: "faiss.Index", big_npy: np.ndarray,
                index_rate: float) -> np.ndarray:
    """§4.5b Index blend: faiss IVFFlat search k=8 (L2), (1/score)² weights,
    feats = index_rate·npy + (1-index_rate)·feats."""
    if index_rate <= 0.0:                                        # blend off -> passthrough
        return feats
    query = np.ascontiguousarray(feats, dtype=np.float32)
    score, ix = index.search(query, k=8)                        # §4.5b IVFFlat k=8, L2 score
    weight = np.square(1.0 / np.maximum(score, 1e-12))          # §4.5b w = (1/score)²
    weight = weight / np.sum(weight, axis=1, keepdims=True)     # §4.5b row-normalize
    npy = np.sum(big_npy[ix] * weight[:, :, np.newaxis], axis=1)  # §4.5b Σ big_npy[ix]·w
    blended = index_rate * npy + (1.0 - index_rate) * feats     # §4.5b blend
    return blended.astype(np.float32)


def upsample_protect(feats_blended: np.ndarray, feats0: np.ndarray,
                     pitch: np.ndarray, pitchf: np.ndarray, pad_len: int,
                     protect: float = 0.33) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """§4.5c ×2 nearest upsample (np.repeat) + pitch-protect 0.33.

    Returns (phone [T,768], pitch [T], pitchf [T]) sliced to the common length.
    """
    phone = np.repeat(feats_blended, 2, axis=0)                 # §4.5c ×2 nearest = np.repeat
    phone0 = np.repeat(feats0, 2, axis=0)                       # index-free copy, same upsample
    # §4.5c p_len = min(len(pad)//160, 2·Tc); slice feats/pitch/pitchf to p_len.
    p_len = min(pad_len // HOP, phone.shape[0])
    p_len = min(p_len, pitch.shape[0], pitchf.shape[0])
    phone = phone[:p_len]
    phone0 = phone0[:p_len]
    pitch = pitch[:p_len]
    pitchf = pitchf[:p_len]
    # §4.5c pitch-protect: pitchff = 1 where pitchf>0 else 0.33.
    pitchff = np.where(pitchf > 0, 1.0, protect).astype(np.float32)[:, np.newaxis]
    phone = phone * pitchff + phone0 * (1.0 - pitchff)          # §4.5c protected blend
    return phone.astype(np.float32), pitch, pitchf


def synth(phone: np.ndarray, pitch: np.ndarray, pitchf: np.ndarray,
          netg_sess: ort.InferenceSession) -> np.ndarray:
    """§4.6 net_g: build the six inputs incl. external rnd ~ N(0,1), run, take
    audio[0,0]. Returns float32 40 kHz waveform."""
    t = phone.shape[0]
    inter_channels = 192                                        # §3 rnd = [1, 192, T]
    rnd = np.random.randn(1, inter_channels, t).astype(np.float32)  # §4.6 external flow noise
    feeds = {
        "phone": phone[np.newaxis, :, :].astype(np.float32),   # §3 [1,T,768]
        "phone_lengths": np.array([t], dtype=np.int64),         # §3 [1] = T
        "pitch": pitch[np.newaxis, :].astype(np.int64),         # §3 [1,T] coarse 1..255
        "nsff0": pitchf[np.newaxis, :].astype(np.float32),      # §3 [1,T] fine f0 Hz
        "sid": np.array([0], dtype=np.int64),                   # §3 [1] speaker id 0
        "rnd": rnd,                                             # §3 [1,192,T]
    }
    audio = netg_sess.run(["audio"], feeds)[0]                  # §4.6 [1,1,T*400] @ 40 kHz
    return audio[0, 0].astype(np.float32)


def postprocess(audio: np.ndarray) -> np.ndarray:
    """§4.7 Trim [40000:-40000]; normalize peak/0.99 if >1."""
    audio = audio[TRIM:-TRIM]                                   # §4.7 trim t_pad_tgt each end
    peak = float(np.abs(audio).max()) if audio.size else 0.0
    audio_max = peak / 0.99                                     # §4.7 normalize peak/0.99
    if audio_max > 1.0:
        audio = audio / audio_max
    return audio.astype(np.float32)


def convert(x_src16k: np.ndarray, index_rate: float, bundle: "VoiceBundle",
            shared: "Shared") -> np.ndarray:
    """Run the full §4 pipeline for one block. Pure given the loaded models.

    x_src16k is already §4.1-loaded (16k mono, normalized). Steps §4.2 .. §4.7.
    """
    x = highpass(x_src16k)                                      # §4.2
    x_pad = reflect_pad(x, T_PAD)                               # §4.3
    pitch, pitchf = f0_rmvpe(x_pad, shared.rmvpe, shared.melbasis)  # §4.4
    feats0 = contentvec_feats(x_pad, shared.contentvec)        # §4.5a (index-free copy)
    feats_blended = index_blend(feats0, bundle.index, bundle.big_npy, index_rate)  # §4.5b
    phone, pitch, pitchf = upsample_protect(                    # §4.5c
        feats_blended, feats0, pitch, pitchf, pad_len=x_pad.shape[0])
    audio = synth(phone, pitch, pitchf, bundle.netg)           # §4.6
    return postprocess(audio)                                  # §4.7


