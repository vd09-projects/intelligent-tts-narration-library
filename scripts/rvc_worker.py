# Model registry — warm-load-once. Shared (voice-independent) loaded eagerly at
# startup; per-voice bundles loaded lazily the first time a voice appears, then
# reused warm. A `LOAD <kind> <slug>` stderr line is printed exactly once each.
# ══════════════════════════════════════════════════════════════════════════════

class Shared:
    """Voice-independent models, loaded once."""

    def __init__(self, contentvec: ort.InferenceSession, rmvpe: ort.InferenceSession,
                 melbasis: np.ndarray) -> None:
        self.contentvec = contentvec
        self.rmvpe = rmvpe
        self.melbasis = melbasis


class VoiceBundle:
    """Per-voice models: net_g generator + faiss index + reconstructed vectors."""

    def __init__(self, netg: ort.InferenceSession, index: "faiss.Index",
                 big_npy: np.ndarray) -> None:
        self.netg = netg
        self.index = index
        self.big_npy = big_npy


def _session_options() -> ort.SessionOptions:
    """ORT options. Single-thread fallback (first-class, default off) wired to
    OMP_NUM_THREADS=1 for the faiss+ORT OpenMP-contention case (review S4)."""
    so = ort.SessionOptions()
    if os.environ.get("OMP_NUM_THREADS") == "1":
        so.intra_op_num_threads = 1                            # single-thread fallback
    return so


def _load_session(path: str) -> ort.InferenceSession:
    if not os.path.isfile(path):
        raise FileNotFoundError(f"missing ONNX artifact: {path}")
    return ort.InferenceSession(path, _session_options(),
                                providers=["CPUExecutionProvider"])


def load_shared(models_root: str) -> Shared:
    """Load contentvec + rmvpe ORT sessions + mel basis once. Startup-fatal if
    any shared artifact is missing (raises -> nonzero exit)."""
    shared_onnx = os.path.join(models_root, "_shared", "onnx")
    contentvec = _load_session(os.path.join(shared_onnx, "contentvec.onnx"))
    rmvpe = _load_session(os.path.join(shared_onnx, "rmvpe.onnx"))
    melbasis_path = os.path.join(shared_onnx, "rmvpe_melbasis.npy")
    if not os.path.isfile(melbasis_path):
        raise FileNotFoundError(f"missing mel basis: {melbasis_path}")
    melbasis = np.load(melbasis_path).astype(np.float32)       # baked 128×513 (§4.4)
    print("LOAD shared _shared", file=sys.stderr, flush=True)
    return Shared(contentvec, rmvpe, melbasis)


def load_voice(slug: str, models_root: str) -> VoiceBundle:
    """Lazily load one voice's net_g + faiss index + reconstructed vectors.
    Logs `LOAD net_g <slug>` / `LOAD index <slug>` exactly once (warm-load proof).
    """
    name = voice_name(slug)
    onnx_dir = os.path.join(models_root, slug, "onnx")
    netg = _load_session(os.path.join(onnx_dir, "net_g.onnx"))
    print(f"LOAD net_g {slug}", file=sys.stderr, flush=True)

    index_path = os.path.join(models_root, slug, f"{name}.index")
    if not os.path.isfile(index_path):
        raise FileNotFoundError(f"missing faiss index: {index_path}")
    index = faiss.read_index(index_path)
    # §4.5b needs big_npy[ix]. The IVFFlat index stores full vectors, so
    # reconstruct them directly (dump_index.py proves reconstruct_n works here).
    # make_direct_map() first in case the index lacks one (cheap, torch-free).
    try:
        index.make_direct_map()
    except Exception:  # noqa: BLE001 - some index types have an implicit direct map
        pass
    big_npy = index.reconstruct_n(0, index.ntotal).astype(np.float32)  # §4.5b stored vectors
    print(f"LOAD index {slug}", file=sys.stderr, flush=True)
    return VoiceBundle(netg, index, big_npy)


