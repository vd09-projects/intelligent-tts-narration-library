FATAL_EXC = (MemoryError,)


def _one_line(text: str) -> str:
    """Collapse newlines/CRs to spaces and cap length — guarantees a single
    physical output line (review B3)."""
    flat = " ".join(str(text).split())
    return flat[:_MSG_CAP]


def _err_line(category: str, message: str) -> str:
    # Every call site passes a literal from the closed ERR set; a miss is a worker
    # bug, not user input. Coerce to the generic in-set category rather than emit an
    # off-contract token — an EXPLICIT guard, not an `assert` that `python -O` strips.
    if category not in ERR_CATEGORIES:
        message = f"[bug: off-contract category {category!r}] {message}"
        category = "infer-failed"
    return f"ERR {category} {_one_line(message)}"


def _atomic_write_wav(audio: np.ndarray, out_path: str) -> None:
    """Write 40 kHz mono s16le WAV atomically: temp in the same dir + os.replace.
    A failed block never leaves a partial WAV at <out> (review S4)."""
    import wave
    max_int16 = 32768.0                                        # match Applio int16 scaling
    pcm = np.clip(audio * max_int16, -32768, 32767).astype(np.int16)
    out_dir = os.path.dirname(os.path.abspath(out_path))
    os.makedirs(out_dir, exist_ok=True)
    tmp_path = f"{out_path}.tmp.{os.getpid()}"
    try:
        with wave.open(tmp_path, "wb") as wav:
            wav.setnchannels(1)
            wav.setsampwidth(2)                                # 16-bit
            wav.setframerate(SR_OUT)                           # 40 kHz
            wav.writeframes(pcm.tobytes())
        os.replace(tmp_path, out_path)                         # atomic swap
    except Exception:
        # clean up the temp so a failed write leaves nothing behind
        try:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
        except OSError:
            pass
        raise


class _Worker:
    """Holds warm models; processes one request line -> one response string."""

    def __init__(self, models_root: str) -> None:
        self.models_root = models_root
        self.shared = load_shared(models_root)
        self.voices: dict[str, VoiceBundle] = {}

    def _voice(self, slug: str) -> VoiceBundle:
        bundle = self.voices.get(slug)
        if bundle is None:
            bundle = load_voice(slug, self.models_root)        # warm-load-once
            self.voices[slug] = bundle
        return bundle

    def handle(self, line: str) -> str:
        """Parse + run one request line. Returns exactly one response line.

        Raises only FATAL_EXC (MemoryError) / BrokenPipeError to the caller;
        every other failure becomes a single-line ERR (the loop survives).
        """
        import shlex

        try:
            parts = shlex.split(line)
        except ValueError as e:
            return _err_line("bad-args", f"unparseable line: {e}")

        if len(parts) != 5:
            return _err_line("bad-args",
                             f"expected 5 tokens <in> <out> <voice> <index_rate> <pitch>, got {len(parts)}")
        in_path, out_path, voice, index_rate_s, pitch_s = parts

        # --- validation (all bad-args / bad-voice) ---
        # Reject a newline/CR-bearing <in> or <out> up front (round-3 #3). A CR can
        # survive CRLF stdin; collapsing it (as _one_line does) would make the OK
        # echo name a DIFFERENT path than _atomic_write_wav wrote to. Rejecting keeps
        # the OK line free to echo the REAL path verbatim (below).
        for _label, _val in (("in", in_path), ("out", out_path)):
            if "\n" in _val or "\r" in _val:
                return _err_line("bad-args", f"<{_label}> contains a newline/CR — paths must be single-line")
        if voice not in ROSTER:
            return _err_line("bad-voice", f"unknown voice '{voice}' (roster: {', '.join(ROSTER)})")
        try:
            index_rate = float(index_rate_s)
        except ValueError:
            return _err_line("bad-args", f"index_rate '{index_rate_s}' is not a float")
        if not (0.0 <= index_rate <= 1.0):
            return _err_line("bad-args", f"index_rate {index_rate} out of range [0,1]")
        try:
            pitch = int(pitch_s)
        except ValueError:
            return _err_line("bad-args", f"pitch '{pitch_s}' is not an int")
        if pitch != 0:
            return _err_line("bad-args", "pitch must be 0 in phase one")

        # --- read (read-failed) ---
        try:
            x_src = load_source(in_path)                        # §4.1
        except FATAL_EXC:
            raise
        except Exception as e:  # noqa: BLE001 - any decode/read error -> recoverable
            return _err_line("read-failed", f"{in_path}: {e}")

        # --- infer (infer-failed). An unexpected mid-DSP exception is classified
        #     infer-failed + continue (recoverable); only FATAL_EXC exits (S4/round-2 #5).
        try:
            bundle = self._voice(voice)                        # may lazily load the voice
            audio = convert(x_src, index_rate, bundle, self.shared)  # §4.2..§4.7
        except FATAL_EXC:
            raise
        except Exception as e:  # noqa: BLE001
            return _err_line("infer-failed", f"{voice}: {e}")

        # --- write (write-failed) ---
        try:
            _atomic_write_wav(audio, out_path)
        except FATAL_EXC:
            raise
        except Exception as e:  # noqa: BLE001
            return _err_line("write-failed", f"{out_path}: {e}")

        # Echo the REAL written path verbatim. Newline/CR were rejected up front
        # (round-3 #3), so this is always a single physical line AND names exactly
        # the file _atomic_write_wav created — the OK name and the file cannot diverge.
        return f"OK {out_path}"


def _emit(response: str) -> None:
    """Print one response line + flush. BrokenPipe propagates (clean exit 0)."""
    sys.stdout.write(response + "\n")
    sys.stdout.flush()


def run_loop(worker: "_Worker") -> int:
    """Service stdin line by line until EOF. One response per input line — a blank
    line is NOT skipped (round-3 #2): it shlex-splits to 0 tokens and yields a
    natural `ERR bad-args`, preserving response-count == request-count. Returns the
    process exit code. The worker is constructed by main() so a startup/construction
    failure is caught there (round-3 #4), not mid-loop."""
    for line in sys.stdin:
        line = line.rstrip("\n")
        response = worker.handle(line)                         # exactly one line back
        _emit(response)
    return 0                                                    # EOF -> clean exit 0


def _parse_args(argv: list[str]) -> argparse.Namespace:
    ap = argparse.ArgumentParser(
        prog="rvc_worker",
        description="Torch-free RVC voice-conversion worker (stdin/stdout line loop).",
    )
    ap.add_argument(
        "--models-root",
        default=os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "assets", "rvc-models",
        ),
        help="root holding _shared/onnx + <slug>/onnx + <slug>/<Name>.index "
             "(default: <repo>/assets/rvc-models).",
    )
    # NOTE: no --mmap. Full-load is the sole shipped path (review S7). --mmap is a
    # documented future option only (see module docstring / scripts/rvc-README).
    return ap.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(sys.argv[1:] if argv is None else argv)

    # Torch-free banner (parity test asserts this exact line; PILOT_REPORT §1).
    print(f"torch imported at inference?: {'torch' in sys.modules}", file=sys.stderr, flush=True)

    # Startup (RVC_SEED parse + load_shared / load-once) is fatal-if-it-raises: emit
    # ONE clean FATAL line + a stable nonzero exit, never a raw traceback (round-3 #4).
    # #145 reads the nonzero exit. A malformed RVC_SEED (int() ValueError) lands in the
    # startup arm too -> FATAL + EXIT_FATAL_STARTUP, not a bare traceback + exit 1.
    # Symmetric with the MemoryError path below.
    try:
        # Optional determinism switch for the parity gate (round-2 #2). Off by default.
        seed = os.environ.get("RVC_SEED")
        if seed is not None:
            np.random.seed(int(seed))
        worker = _Worker(args.models_root)
    except FATAL_EXC as e:
        print(f"FATAL {type(e).__name__}: {_one_line(str(e))}", file=sys.stderr, flush=True)
        return EXIT_FATAL_RUNTIME
    except Exception as e:  # noqa: BLE001 — bad RVC_SEED / missing artifact / torch present / bad venv
        print(f"FATAL {type(e).__name__}: {_one_line(str(e))}", file=sys.stderr, flush=True)
        return EXIT_FATAL_STARTUP

    try:
        return run_loop(worker)
    except BrokenPipeError:
        # Parent closed the pipe — clean exit 0 (review S4). Silence the final
        # flush-on-exit BrokenPipe by redirecting stdout to devnull.
        try:
            devnull = os.open(os.devnull, os.O_WRONLY)
            os.dup2(devnull, sys.stdout.fileno())
        except OSError:
            pass
        return 0
    except FATAL_EXC as e:
        # Catchable fatal (e.g. MemoryError) -> stderr + nonzero exit, NOT ERR (S4).
        print(f"FATAL {type(e).__name__}: {_one_line(str(e))}", file=sys.stderr, flush=True)
        return EXIT_FATAL_RUNTIME


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
