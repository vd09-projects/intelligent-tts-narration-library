#!/usr/bin/env python3
"""Torch-free RVC voice-conversion worker (issue #144, P1 of the RVC chain).

Ephemeral per-job worker. Loads the #143-exported ONNX models + faiss index ONCE
(module globals, warm across every block), then services a stdin/stdout line loop,
converting one WAV per line until EOF, then exits -> 0 idle RAM. This is the shared
engine the future Go decorator (#145) drives as a subprocess; this file owns only
the Python worker. Invoked via `scripts/rvc` (which activates .venv-rvc).

Engine-faithful reproduction of PILOT_REPORT §4 DSP
(research/rvc-voice-conversion-integration/pilot-evidence/PILOT_REPORT.md). No
DSP redesign — every magic constant cites its §4.x subsection.

═══════════════════════════════════════════════════════════════════════════════
WIRE PROTOCOL (v1) — the load-bearing public surface #145 binds to
═══════════════════════════════════════════════════════════════════════════════
Read stdin line by line. Each line is shlex-split into EXACTLY 5 positional
tokens:

    <in> <out> <voice> <index_rate> <pitch>

  <in>          path to a source WAV (any sr/channels; decoded + resampled to 16k)
  <out>         path to write the 40 kHz mono s16le result WAV (written atomically)
  <voice>       one of the roster slugs: cool-jahns | confident-neal
  <index_rate>  float in [0.0, 1.0] — faiss retrieval blend; AUTHORITATIVE per line
  <pitch>       int; MUST be 0 in phase one (non-zero is rejected, no transpose)

RESPONSES — exactly ONE physical line per request (response count == request count):

  OK <out>                      success; the WAV now exists at <out>
  ERR <category> <message>      recoverable per-line failure; the loop continues

  <category> is a CLOSED set:
      bad-args | bad-voice | read-failed | infer-failed | write-failed
  <message> has all newlines/CRs collapsed to spaces and is capped at 300 chars,
  so an ERR is ALWAYS a single line (framing #145 relies on). A newline/CR-bearing
  <in> or <out> is REJECTED up front as `ERR bad-args` (paths must be single-line),
  so the `OK <out>` line echoes the REAL written path VERBATIM — the OK name and the
  file on disk can never diverge.

  #145 branches retryable-vs-fatal on the <category> token alone, without parsing
  the free-text message. An unknown category (forward-compat) is treated as fatal.

FRAMING / FORWARD-COMPAT: the 5-token line is positional and append-only — never
reorder or repurpose a token. Future capability (e.g. non-zero pitch, windowing)
is a trailing optional token with an engine-faithful default. The ERR category
set is append-only.

PROCESS SEMANTICS:
  EOF on stdin                  -> clean exit 0 (models freed, 0 idle RAM)
  BrokenPipeError writing out   -> clean exit 0 (the parent closed the pipe)
  MemoryError / catchable fatal -> stderr + NONZERO exit (NOT a per-block ERR)
  missing shared artifact,      -> stderr + NONZERO exit (startup fatal)
    torch present, bad venv
  native fault (segfault)       -> process dies with a nonzero signal exit
    (uncatchable in Python; documented, relied upon)

Models load once. A `LOAD <kind> <slug>` line is printed to stderr exactly once
per (kind, voice) — proof of warm-load-once across a multi-block batch.

ENV SWITCHES (both first-class, default OFF):
  OMP_NUM_THREADS=1   -> single-thread mode: ORT intra_op_num_threads=1
                         (pre-wired fallback for the faiss+ORT OpenMP-contention
                         case; default is ORT multithreaded, safe because torch —
                         the other libomp — is never imported).
  RVC_SEED=<int>      -> seed numpy RNG at startup so the external net_g flow noise
                         (`rnd`) is deterministic. Used by `make rvc-parity` so the
                         full-pipeline log-mel gate is reproducible, not flaky. The
                         SECOND, internal net_g RandomNormalLike (NSF sine dither,
                         std ~0.003) is generated by onnxruntime per run and is NOT
                         seedable from Python — it is the ~0.0009-RMS parity floor,
                         well inside the 0.98 log-mel corr gate.

DEFERRED (documented, NOT shipped): a `--mmap` model-load flag. Full-load is the
sole shipped path and what parity judges (review S7). Do not add a half-wired flag.

Timeouts (60s/block, 10min/wall) are the Go caller's (#145) job, not the worker's.

See scripts/rvc-README for install + failure-mode reference.
"""

